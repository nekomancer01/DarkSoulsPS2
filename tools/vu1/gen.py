def gen_fx():
    assert FX_OUT1 + FX_OUT_QW <= 1014 and FX_N % FX_P == 0 and FX_KICK % FX_P == 0
    code = []
    for j in range(FX_P):
        code += fx_particle(j)
    code += ['L iaddiu VI03, VI03, %d' % (2 * FX_P), 'L iaddiu VI06, VI06, %d' % (12 * FX_P),
             'L isubiu VI04, VI04, %d' % FX_P]
    pool = ['VF%02d' % i for i in range(13, 32)]
    pairs, per, stalls, b = schedule_body(code, ['VI01', 'VI10', 'VI11', 'VI12', 'VI13', 'VI14', 'VI15'],
                                          'fxPart', 'ibne VI04, VI00, fxPart', pool)
    print('fx: body %d pairs, %.1f cycles / particle, stalls %d' % (len(pairs), per / FX_P, stalls), file=sys.stderr)
    out = [FX_DOC, '; loop: %.0f cycles per particle in the tools/vu1 timing model (%d per pass)' % (per / FX_P, FX_P),
           '; layout: FX_IN %d (%d qw each), FX_OUT0 %d, FX_OUT1 %d (%d qw each), end %d' %
           (FX_IN, FX_IN_QW, FX_OUT0, FX_OUT1, FX_OUT_QW, FX_OUT1 + FX_OUT_QW),
           '', '\t\t.vu', '\t\t.align 4', '\t\t.global VU1Fx_CodeStart', '\t\t.global VU1Fx_CodeEnd',
           'VU1Fx_CodeStart:']
    P = lambda u, l='NOP': out.append('\t%-31s\t%s' % (u.replace(', ', ','), l.replace(', ', ',')))
    for k in range(6):
        P('NOP', 'lq VF%02d, %d(VI00)' % (k + 1, k))
    P('NOP', 'xtop VI02')
    for k in range(6):                                  # VF07 .. VF12: batch header 1-6
        P('NOP', 'lq VF%02d, %d(VI02)' % (k + 7, k + 1))
    P('NOP', 'ilw.x VI07, 0(VI02)')
    P('NOP', 'iaddiu VI01, VI00, %d' % FX_OUT1)
    P('NOP', 'iaddiu VI05, VI02, 7')
    P('NOP', 'xgkick VI05')                             # A+D header straight from the input buffer
