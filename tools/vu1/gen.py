"""Generate the software-pipelined VU1 programs of ps2/proto (F1): python3 gen.py skin > ps2/proto/src/vu1skin2.vsm
The per-triangle loop body is written below as straight-line code (3 vertices, stage by stage so the accumulate
chains of the three vertices follow each other) with virtual registers, then list-scheduled and register-allocated
by vucore.Block. Everything else (batch setup, kick groups) is written by hand. The scheduler's cycle count is printed
to stderr and written into the file header."""
import re
import sys
from vucore import Block, verify

VF_POOL = ['VF%02d' % i for i in range(8, 32)]


def emit_pairs(pairs, out, indent='\t'):
    for u, l in pairs:
        out.append('%s%-31s\t%s' % (indent, u.replace(', ', ','), l.replace(', ', ',')))


# ------------------------------------------------------------------------------------------------ skin
SKIN_DOC = """; VU1 microprogram (generated by tools/vu1/gen.py skin, do not edit): skinned character triangles, two bones per
; vertex, lit, projected, culled; software pipelined (F1): one loop pass per triangle, its three vertices interleaved.
; Input and output live in separate buffers (fixes the XGKICK-overwrite hazard of the in-place layout).
;
; VU1 data memory (skin pass, vu1.c): 0-7 constants, bone palette 8 + 4 b (b < 61), input double buffer at
; SKIN_IN (BASE/OFFSET, xtop), two output slots SKIN_OUT0 / SKIN_OUT1 of 1 + 9 SKIN_KICK qwords. VI08 keeps the
; slot to fill next across batches (any other value means slot 0); every kick of SKIN_KICK triangles switches slot,
; so a slot is refilled only after the next kick, which waits for the previous one to finish.
; Constants: 4 scale (F, -F, Zs, fog a), 5 offset (cx, cy, 0, fog b), 6 clip scale (F/G, F/G, 2 near, fog min),
; 7 (0, 0, -1, fog max). Bone b: columns of view * world, col0-2 .w = bone-space light vector.
; Batch (input buffer): 0 {tris, cull mask}, 1 K1, 2 K2, 3 clamp (255, 255, 255, 128), 4 A+D GIF tag (EOP),
; 5-7 TEX0 / TEX1 / TEST, 8 PRIM GIF tag template (STQ, RGBAQ, XYZF2; NLOOP / EOP filled per kick),
; 9.. vertices of 4 qwords: pa, pb (s16 x, y, z / 4096 + palette offset 4 b), normal + weight A (s16 / 4096),
; st (f32) or colour (u8).
; Textured: colour = min(K1 + K2 max(n . L, 0), clamp) with K1 = tint + 64, K2 = 96 (= 0x80 (0.5 + 0.75 n.L)).
; Flat: colour = min(tint + base (0.5 + 0.75 max(n . L, 0)), clamp) with K1 = tint, K2 = (0.5, 0.75).
; Per vertex: view = w A pa + (1 - w) B pb; q = 1 / view z; screen = (x q, y q, q) * scale + offset; fog .w =
; clamp(a z + b); CLIP of (x q F/G, y q F/G, 2 near q - 1) against 1 flags near / guard-band vertices (triangle
; skipped with ADC, as before); back faces: sign / zero of -((B - A) x (C - A)).z on screen, caught by the cull mask.
"""


def skin_vertex_stages(flat, spec=False):
    """List of stages; each stage is a function v -> list of instruction lines for vertex v (0..2)."""
    def s_load(v):
        o = 4 * v
        c = ['L ilw.w &ba%d, %d(VI03)' % (v, o), 'L ilw.w &bb%d, %d(VI03)' % (v, o + 1),
             'L lq %%pa%d, %d(VI03)' % (v, o), 'L lq %%pb%d, %d(VI03)' % (v, o + 1), 'L lq %%nm%d, %d(VI03)' % (v, o + 2),
             'L lq %%st%d, %d(VI03)' % (v, o + 3),
             'U itof12.xyz %%pa%d, %%pa%d' % (v, v), 'U itof12.xyz %%pb%d, %%pb%d' % (v, v), 'U itof12 %%nm%d, %%nm%d' % (v, v)]
        if flat:
            c.append('U itof0 %%st%d, %%st%d' % (v, v))
        c += ['L lq %%a%d%d, %d(&ba%d)' % (k, v, 8 + k, v) for k in range(4)]
        c += ['L lq %%b%d%d, %d(&bb%d)' % (k, v, 8 + k, v) for k in range(4)]
        return c

    def s_xa(v):
        return ['U mulax ACC, %%a0%d, %%pa%d:x' % (v, v), 'U madday ACC, %%a1%d, %%pa%d:y' % (v, v),
                'U maddaz ACC, %%a2%d, %%pa%d:z' % (v, v), 'U maddw %%va%d, %%a3%d, VF00w' % (v, v)]

    def s_xb(v):
        return ['U mulax ACC, %%b0%d, %%pb%d:x' % (v, v), 'U madday ACC, %%b1%d, %%pb%d:y' % (v, v),
                'U maddaz ACC, %%b2%d, %%pb%d:z' % (v, v), 'U maddw %%vb%d, %%b3%d, VF00w' % (v, v)]

    def s_nl(v):  # .w = n . L (bone space); textured also .xyz = view-space normal (bone A rotation) for specular
        f = '' if spec else '.w'
        return ['U mulax%s ACC, %%a0%d, %%nm%d:x' % (f, v, v), 'U madday%s ACC, %%a1%d, %%nm%d:y' % (f, v, v),
                'U maddz%s %%nl%d, %%a2%d, %%nm%d:z' % (f, v, v, v)]

    def s_blend(v):
        return ['U sub.xyz %%d%d, %%va%d, %%vb%d' % (v, v, v), 'U adda.xyz ACC, %%vb%d, VF00' % v,
                'U maddw.xyz %%v%d, %%d%d, %%nm%d:w' % (v, v, v)]

    def s_fog(v):
        return ['U mulaw.w ACC, VF04, VF00w', 'U maddz.w %%f%d, VF03, %%v%d:z' % (v, v),
                'U max.w %%f%d, %%f%d, VF05' % (v, v), 'U mini.w %%f%d, %%f%d, VF06' % (v, v)]

    def s_light(v):
        if flat:
            return ['U maxx.w %%nl%d, %%nl%d, VF00x' % (v, v),
                    'U mulax.w ACC, VF00, VF02x', 'U maddy.w %%nl%d, %%nl%d, VF02y' % (v, v),
                    'U mulaw ACC, VF01, VF00w', 'U maddw %%c%d, %%st%d, %%nl%d:w' % (v, v, v),
                    'U mini %%c%d, %%c%d, VF07' % (v, v), 'U ftoi0 %%c%d, %%c%d' % (v, v)]
        if not spec:
            return ['U maxx.w %%nl%d, %%nl%d, VF00x' % (v, v),
                    'U mulaw ACC, VF01, VF00w', 'U maddw %%c%d, VF02, %%nl%d:w' % (v, v),
                    'U mini %%c%d, %%c%d, VF07' % (v, v), 'U ftoi0 %%c%d, %%c%d' % (v, v)]
        # K1 + K2 n.L - m (amb + K2 n.L) + f spec: with m = f = 0 bit-identical to the textured entry
        return ['U maxx.w %%nl%d, %%nl%d, VF00x' % (v, v), 'U mulz.w %%mnl%d, %%nl%d, %%ms%d:z' % (v, v, v),
                'L lq %%amb%d, %d(VI00)' % (v, SPEC + 7), 'L lq %%sun%d, %d(VI00)' % (v, SPEC + 8),
                'U mulaw ACC, VF01, VF00w', 'U maddaw ACC, VF02, %%nl%d:w' % v,
                'U msubaz ACC, %%amb%d, %%ms%d:z' % (v, v), 'U msubaw ACC, %%sun%d, %%mnl%d:w' % (v, v),
                'U maddw %%c%d, %%sp%d, %%ms%d:w' % (v, v, v),
                'U mini %%c%d, %%c%d, VF07' % (v, v), 'U ftoi0 %%c%d, %%c%d' % (v, v)]

    def s_q(v):
        c = ['L div Q, VF00w, %%v%d:z' % v, 'L waitq', 'U mulq.xy %%p%d, %%v%d, Q' % (v, v), 'U addq.z %%p%d, VF00, Q' % v]
        if not flat:
            c += ['U mulq.xy %%st%d, %%st%d, Q' % (v, v), 'U addq.z %%st%d, VF00, Q' % v]
        return c

    def s_clip(v):
        return ['U mula.xyz ACC, %%p%d, VF05' % v, 'U maddw.xyz %%cl%d, VF06, VF00w' % v,
                'U clipw.xyz %%cl%d:xyz, VF00w' % v]

    def s_screen(v):
        o = 3 * v
        return ['U mulaw.xyz ACC, VF04, VF00w', 'U madd.xyz %%f%d, %%p%d, VF03' % (v, v), 'U ftoi4 %%fi%d, %%f%d' % (v, v),
                'L sq %s, %d(VI06)' % ('%%p%d' % v if flat else '%%st%d' % v, o),
                'L sq %%c%d, %d(VI06)' % (v, o + 1), 'L sq %%fi%d, %d(VI06)' % (v, o + 2)]

    if not spec:
        return [s_load, s_xa, s_xb, s_nl, s_blend, s_fog, s_light, s_q, s_clip, s_screen]
    return [const_loads(f) for f in [s_load, s_xa, s_xb, s_nl, s_blend] + spec_stages() +
            [s_fog, s_light, s_q, s_clip, s_screen]]


# textured skin: the batch / pass constants are loaded where they are used (lower pipe) instead of living in
# VF01-VF07, so the register allocator has 29 registers for the specular temporaries
CONST_ADDR = {1: '1(VI02)', 2: '2(VI02)', 7: '3(VI02)', 3: '4(VI00)', 4: '5(VI00)', 5: '6(VI00)', 6: '7(VI00)'}


def const_loads(stage):
    def f(v):
        lines = stage(v)
        used = sorted({int(m) for l in lines for m in re.findall(r'\bVF0([1-7])[xyzw]?\b', l)})
        tag = '%s%d' % (stage.__name__, v)
        out = ['L lq %%K%d_%s, %s' % (k, tag, CONST_ADDR[k]) for k in used]
        for l in lines:
            out.append(re.sub(r'\bVF0([1-7])([xyzw]?)\b',
                              lambda m: '%%K%s_%s' % (m.group(1), tag) + (':' + m.group(2) if m.group(2) else ''), l))
        return out
    f.__name__ = stage.__name__
    return f


# Specular constant block (skin pass, written per draw by vu1_skin_begin; view space): 0-2 Mn_k = (Ls_k, 2 Up_k,
# Vc_k, Hc_k) with Vc = towards the camera from the character's centre, Hc = normalize(Ls + Vc); 3 (BIG, -Vc.Up, 0, 0);
# 4 Ec = (EnvUp + EnvDown) / 2, 5 Eh = (EnvUp - EnvDown) / 2, 6 SpecI, 7 amb, 8 sun (colours x 1/255: m and f arrive as
# 0..255, colour lanes .w = 0), 9 Eh / 2. Batch header 0.zw = (a, b): d = max(0, a n.H + b)^2 ~ (n.H)^(2^k) (vu1.c).
SPEC = 992
SPEC_QW = 10  # 9: Eh / 2 (vu1skinclip's exact path)


def spec_stages():
    """Textured skin specular, cheap form (opt-vu1 2026-10-31, replacing the exact per-vertex V / H one): V is the
    character's centre direction for the whole draw, so H = normalize(Ls + V) is a per-draw constant and n.Ls, n.Up,
    n.V, n.H come from one 3-op dot chain on the view-space normal (%nl.xyz; bone A rotation, orthonormal).
    d = max(0, a c + b)^2 with c = max(n.H, 0), 0 where n.Ls <= 0; R.y = 2 (n.V)(n.Up) - V.Up (|R| = 1, no clamp):
    env = Ec + Eh R.y; spec = env + SpecI d. No EFU, no divide."""
    ld = lambda name, v, k: 'L lq %%%s%d, %d(VI00)' % (name, v, SPEC + k)

    def ms(v):
        return ['U itof0.zw %%ms%d, %%st%d' % (v, v)]  # m, f x 255 (the 1/255 sits in Ec, Eh, SpecI, amb, sun)

    def dmat(v):  # D = (n.Ls, 2 n.Up, n.V, n.H)
        return [ld('mn%d_' % k, v, k) for k in range(3)] + [
            'U mulax ACC, %%mn0_%d, %%nl%d:x' % (v, v), 'U madday ACC, %%mn1_%d, %%nl%d:y' % (v, v),
            'U maddz %%D%d, %%mn2_%d, %%nl%d:z' % (v, v, v)]

    def cpow(v):  # c.w = clamp(n.H, 0, n.Ls BIG); d.w = max(0, a c + b)^2
        return [ld('cs', v, 3), 'L lq %%h0_%d, 0(VI02)' % v,
                'U mulx.x %%g%d, %%D%d, %%cs%d:x' % (v, v, v), 'U minix.w %%c%d, %%D%d, %%g%d:x' % (v, v, v),
                'U maxx.w %%c%d, %%c%d, VF00x' % (v, v),
                'U mulaw.w ACC, %%h0_%d, VF00w' % v, 'U maddz.w %%t%d, %%c%d, %%h0_%d:z' % (v, v, v),
                'U maxx.w %%t%d, %%t%d, VF00x' % (v, v), 'U mul.w %%dd%d, %%t%d, %%t%d' % (v, v, v)]

    def env(v):  # R.y = 2 (n.Up)(n.V) - V.Up; env = Ec + Eh R.y; spec = env + SpecI d
        return [ld('cr', v, 3), ld('ec', v, 4), ld('eh', v, 5), ld('si', v, 6),
                'U mulaw.y ACC, %%cr%d, VF00w' % v, 'U maddz.y %%ry%d, %%D%d, %%D%d:z' % (v, v, v),
                'U mulaw ACC, %%ec%d, VF00w' % v, 'U maddy %%env%d, %%eh%d, %%ry%d:y' % (v, v, v),
                'U mulaw ACC, %%env%d, VF00w' % v, 'U maddw %%sp%d, %%si%d, %%dd%d:w' % (v, v, v)]

    return [ms, dmat, cpow, env]


def skin_body(flat, split=None, spec=False):
    """split: stages before index split run stage-major (vertices interleaved in source order), the rest
    vertex-major (fewer values live at once: the specular stages need ~10 registers per vertex)."""
    code = []
    stages = skin_vertex_stages(flat, spec)
    a, b = (len(stages), len(stages)) if split is None else split  # stages a..b-1 vertex-major
    for st in stages[:a]:
        for v in range(3):
            code += st(v)
    for v in range(3):
        for st in stages[a:b]:
            code += st(v)
    for st in stages[b:]:
        for v in range(3):
            code += st(v)
    code += ['U sub.xyz %e1, %f1, %f0', 'U sub.xyz %e2, %f2, %f0',
             'U opmula.xyz ACC, %e2, %e1', 'U opmsub.xyz %cr, %e1, %e2',
             'L fcand VI01, 262143', 'L fmand &fm, VI05',
             'L ior &t, VI01, &fm', 'L iaddiu &t, &t, 0x7fff', 'L iand &t, &t, VI09',
             'L mtir &w, %fi2:w', 'L ior &t, &t, &w', 'L isw.w &t, 8(VI06)',
             'L iaddiu VI03, VI03, 12', 'L iaddiu VI06, VI06, 9', 'L isubiu VI04, VI04, 1']
    return code


# register-pressure settings tried by schedule_body (reserve registers, lookahead window); the shortest wins.
# FULL_SEARCH (gen.py ... --search) tries them all with every source order; otherwise the quick lists below, which
# hold the winners of the last full search (2026-10-31 15:00: Tex (3, 60) 132, TexSpec split (5, 14) at (6, 20) 198,
# Flat 135 cycles / triangle)
FULL_SEARCH = '--search' in sys.argv
QUICK_SETTINGS = ((0, 10 ** 9), (6, 20), (3, 60), (99, 40))  # same order as SCHED_SETTINGS (ties)
SCHED_SETTINGS = ((0, 10 ** 9), (6, 20), (3, 60), (6, 60), (10, 60), (99, 150), (99, 100), (99, 70), (99, 50),
                  (99, 40), (99, 30), (99, 20), (99, 8))


def schedule_body(code, vi_pool, label, branch, vf_pool=None):
    """Schedule with a few register-pressure settings; keep the shortest schedule that does not deadlock."""
    best = None
    for reserve, window in (SCHED_SETTINGS if FULL_SEARCH else QUICK_SETTINGS):
        b = Block(code, vf_pool or VF_POOL, vi_pool)
        try:
            b.schedule(reserve=reserve, window=window)
        except RuntimeError:
            continue
        if '-v' in sys.argv:
            print('    setting %s: %d' % ((reserve, window), b.length), file=sys.stderr)
        if best is None or b.length < best.length:
            best = b
    if best is None:
        raise RuntimeError('no schedule fits the register pools')
    b = best
    bad = b.check_flags()
    if bad:
        raise RuntimeError('\n'.join(bad))
    b.allocate()
    pairs = b.pairs(branch=branch)
    per, stalls, _ = verify(pairs)
    return pairs, per, stalls, b


SKIN_KICK = 8
SKIN_TRIS = 24
SKIN_IN = 252
SKIN_IN_SIZE = 9 + 12 * SKIN_TRIS
SKIN_OUT0 = SKIN_IN + 2 * SKIN_IN_SIZE
SKIN_OUT_SIZE = 1 + 9 * SKIN_KICK
SKIN_OUT1 = SKIN_OUT0 + SKIN_OUT_SIZE


SKIN_MODES = (('Tex', 0, False), ('TexSpec', 0, True), ('Flat', 1, False))
SPEC_SPLITS = ((5, 14),)  # quick mode: the textured-specular source order of the last full search


def gen_skin():
    assert SKIN_OUT1 + SKIN_OUT_SIZE <= 1024
    out = [SKIN_DOC]
    out.append('; layout: SKIN_IN %d (%d qw each), SKIN_OUT0 %d, SKIN_OUT1 %d (%d qw each), end %d' %
               (SKIN_IN, SKIN_IN_SIZE, SKIN_OUT0, SKIN_OUT1, SKIN_OUT_SIZE, SKIN_OUT1 + SKIN_OUT_SIZE))
    bodies = {}
    # entries: textured (no m / f stream: no specular), textured + specular (SKIN_MODES), flat
    for tag, flat, spec in SKIN_MODES:
        vi_pool = ['VI10', 'VI11', 'VI12', 'VI13', 'VI14', 'VI15']
        lab = 'skin2Tri%s' % tag
        # specular: VF01-VF07 are free (const_loads loads the constants where they are used)
        pool = ['VF%02d' % i for i in range(1, 8)] + VF_POOL if spec else VF_POOL
        nst = len(skin_vertex_stages(flat, spec))
        splits = (None,) if not spec else ((5, 9), (5, nst), (0, 9), (0, nst), None) if FULL_SEARCH else SPEC_SPLITS
        best = None
        for split in splits:
            try:
                r = schedule_body(skin_body(flat, split, spec), vi_pool, lab, 'ibne VI04, VI00, %s' % lab, pool)
            except RuntimeError:
                continue
            print('  split %s: %.0f cycles / triangle' % (split, r[1]), file=sys.stderr)
            if best is None or r[1] < best[1]:
                best = r
        pairs, per, stalls, b = best
        bodies[tag] = (pairs, per, stalls, lab)
        print('skin %s: body %d pairs, %.1f cycles / triangle (%.1f / vertex), stalls %d' %
              (tag, len(pairs), per, per / 3, stalls), file=sys.stderr)
        out.append('; %s loop: %.0f cycles per triangle (%.1f per vertex) in the tools/vu1 timing model' %
                   (tag, per, per / 3))
    out += ['', '\t\t.vu', '\t\t.align 4', '\t\t.global VU1Skin2_CodeStart', '\t\t.global VU1Skin2_CodeEnd'] + \
        ['\t\t.global VU1Skin2_%s' % t for t, f, s in SKIN_MODES] + ['VU1Skin2_CodeStart:']
    for tag, flat, spec in SKIN_MODES:
        pairs, per, stalls, lab = bodies[tag]
        P = lambda u, l='NOP': out.append('\t%-31s\t%s' % (u.replace(', ', ','), l.replace(', ', ',')))
        out.append('VU1Skin2_%s:' % tag)
        P('NOP', 'lq VF03, 4(VI00)')
        P('NOP', 'lq VF04, 5(VI00)')
        P('NOP', 'lq VF05, 6(VI00)')
        P('NOP', 'lq VF06, 7(VI00)')
        P('NOP', 'xtop VI02')
        P('NOP', 'iaddiu VI01, VI00, %d' % SKIN_OUT1)
        P('NOP', 'ilw.x VI07, 0(VI02)')
        P('NOP', 'ilw.y VI05, 0(VI02)')
        P('NOP', 'lq VF01, 1(VI02)')
        P('NOP', 'lq VF02, 2(VI02)')
        P('NOP', 'lq VF07, 3(VI02)')
        P('NOP', 'iaddiu VI06, VI02, 4')
        P('NOP', 'xgkick VI06')                     # A+D header straight from the input buffer
        P('NOP', 'iaddiu VI03, VI02, 9')
        P('NOP', 'iaddiu VI09, VI00, 0x7fff')
        P('NOP', 'ibeq VI08, VI01, skin2Grp%s' % tag)   # VI08 is a valid slot (1) or becomes slot 0
        P('NOP', 'iaddiu VI09, VI09, 1')
        P('NOP', 'iaddiu VI08, VI00, %d' % SKIN_OUT0)
        out.append('skin2Grp%s:' % tag)                 # kick group: g = min(SKIN_KICK, left)
        P('NOP', 'iaddiu VI04, VI00, %d' % SKIN_KICK)
        P('NOP', 'isubiu VI01, VI07, %d' % SKIN_KICK)
        P('NOP', 'lq VF08, 8(VI02)')
        P('NOP', 'ibgez VI01, skin2Full%s' % tag)
        P('NOP', 'iaddiu VI06, VI08, 1')
        P('NOP', 'iadd VI04, VI07, VI00')
        out.append('skin2Full%s:' % tag)
        P('NOP', 'isub VI07, VI07, VI04')
        P('NOP', 'iadd VI01, VI04, VI04')
        P('NOP', 'iadd VI01, VI01, VI04')
        P('NOP', 'ior VI01, VI01, VI09')
        P('NOP', 'sq VF08, 0(VI08)')
        P('NOP', 'isw.x VI01, 0(VI08)')               # PRIM tag: NLOOP = 3 g, EOP
        out.append('%s:' % lab)
        emit_pairs(pairs, out)
        P('NOP', 'NOP')
        P('NOP', 'xgkick VI08')
        P('NOP', 'iaddiu VI01, VI00, %d' % (SKIN_OUT0 + SKIN_OUT1))
        P('NOP', 'isub VI08, VI01, VI08')
        P('NOP', 'ibne VI07, VI00, skin2Grp%s' % tag)
        P('NOP', 'NOP')
        P('NOP[E]', 'NOP')
        P('NOP', 'NOP')
    out += ['\t\t.align 4', 'VU1Skin2_CodeEnd:', '']
    return '\n'.join(out)


