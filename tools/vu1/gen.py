MAP_DOC = """; VU1 microprogram (generated by tools/vu1/gen.py map, do not edit): textured gouraud triangle lists for map chunks,
; software pipelined (F1): one loop pass per triangle, its three vertices interleaved by tools/vu1's list scheduler.
; Input (R3, same as vu1clip.vsm): header 0 {tris, cull mask, st scale K, edge fog slope a2 (0: none)}, 1 {chunk origin xyz, position step},
; 2 A+D GIF tag (EOP), 3-5 TEX0 / TEX1 / TEST, 6 PRIM tag with NLOOP 3 + EOP; vertices at 7, 3 qw each: s16 pos,
; u16 st, u8 colour. Constants: 0-3 view matrix columns with .w = the z row (so view .w = view z for CLIP), 4 scale
; (F, -F, Zs, fog a), 5 offset (cx, cy, 0, fog b), 6 (F/G, F/G, 1, fog min), 7 (0, 0, -2 near, fog max).
; Per vertex: view = M' itof(pos) (M' = M with origin / step folded in per batch); fog = clamp(a z + b), then the edge
; fog max(min(fog, b + a2 z), 0) with a2 = header 0.w, in a second loop taken when the low 16 bits of header 0.w are not
; 0 (map.c sets bit 0 for far batches: fades the map out by its cull distance); q = 1 / z;
; STQ = (n q, m q, K q); screen = (x q, y q, q) * scale + offset; CLIP of (x F/G, y F/G, z - 2 near) against z.
; Per triangle: ADC on the third vertex when any vertex is flagged (such batches go to vu1clip.vsm, VU1_CLIP; here it
; only guards against bad boxes) or the cull mask catches the screen cross product. Output: every triangle is its
; own GIF packet in output slot VI08 (%(O0)d / %(O1)d, alternating; shared with vu1clip.vsm), so input and output are
; separate and VIF never overwrites data a kick is still reading.
""" % dict(O0=MAP_OUT0, O1=MAP_OUT1)


def map_body(edge=False, idx=False):
    """vu1map2's triangle; idx: the corners are gathered through the triangle stream at VI03 (vu1mapi's input
    layout, vertices at MAPI_HDR + 3 n)"""
    code = []
    def per(f):
        for v in range(3):
            code.extend(f(v))
    if idx:
        code += ['L ilw.%s &i%d, 0(VI03)' % ('xyz'[v], v) for v in range(3)]
        for v in range(3):
            code += ['L iadd &e%d, &i%d, &i%d' % (v, v, v), 'L iadd &e%d, &e%d, &i%d' % (v, v, v),
                     'L iadd &a%d, &e%d, VI02' % (v, v)]
        src = lambda v, k: '%d(&a%d)' % (MAPI_HDR + k, v)
    else:
        src = lambda v, k: '%d(VI03)' % (3 * v + k)
    o = lambda v, k: 3 * v + k
    per(lambda v: ['L lq %%p%d, %s' % (v, src(v, 0)), 'L lq %%t%d, %s' % (v, src(v, 1)),
                   'L lq %%c%d, %s' % (v, src(v, 2)),
                   'U itof0.xyz %%p%d, %%p%d' % (v, v), 'U itof0.xy %%t%d, %%t%d' % (v, v)])
    per(lambda v: ['U mulax ACC, VF01, %%p%d:x' % v, 'U madday ACC, VF02, %%p%d:y' % v,
                   'U maddaz ACC, VF03, %%p%d:z' % v, 'U maddw %%v%d, VF04, VF00w' % v])
    per(lambda v: ['U mulaw.w ACC, VF06, VF00w', 'U maddz.w %%f%d, VF05, %%v%d:z' % (v, v),
                   'U max.w %%f%d, %%f%d, VF07' % (v, v), 'U mini.w %%f%d, %%f%d, VF08' % (v, v)] +
                  # edge fog (render-distance): e = b + a2 z (a2 = header 0.w, view .w = z); fog = max(min(fog, e), 0)
                  (['U mulaw.w ACC, VF06, VF00w', 'U maddw.w %%g%d, %%v%d, VF09w' % (v, v),
                    'U mini.w %%f%d, %%f%d, %%g%d' % (v, v, v), 'U maxx.w %%f%d, %%f%d, VF00x' % (v, v)] if edge else []))
    per(lambda v: ['U mula.xyz ACC, %%v%d, VF07' % v, 'U maddw.xyz %%cl%d, VF08, VF00w' % v,
                   'U clipw.xyz %%cl%d:xyz, %%v%d:w' % (v, v)])
    per(lambda v: ['L div Q, VF00w, %%v%d:z' % v, 'L waitq', 'U mulq.xy %%q%d, %%v%d, Q' % (v, v),
                   'U addq.z %%q%d, VF00, Q' % v, 'U mulq.xy %%t%d, %%t%d, Q' % (v, v), 'U mulq.z %%t%d, VF09, Q' % v])
    per(lambda v: ['U mulaw.xyz ACC, VF06, VF00w', 'U madd.xyz %%f%d, %%q%d, VF05' % (v, v),
                   'U ftoi4 %%fi%d, %%f%d' % (v, v),
                   'L sq %%t%d, %d(VI08)' % (v, 1 + o(v, 0)), 'L sq %%c%d, %d(VI08)' % (v, 1 + o(v, 1)),
                   'L sq %%fi%d, %d(VI08)' % (v, 1 + o(v, 2))])
    code += ['U sub.xyz %e1, %f1, %f0', 'U sub.xyz %e2, %f2, %f0',
             'U opmula.xyz ACC, %e2, %e1', 'U opmsub.xyz %cr, %e1, %e2',
             'L fcand VI01, 262143', 'L fmand &fm, VI05', 'L ior &t, VI01, &fm', 'L iaddiu &t, &t, 0x7fff',
             'L iand &t, &t, VI09', 'L mtir &w, %fi2:w', 'L ior &t, &t, &w', 'L isw.w &t, 9(VI08)',
             'L sq VF10, 0(VI08)', 'L xgkick VI08', 'L isub VI08, VI06, VI08',
             'L iaddiu VI03, VI03, %d' % (1 if idx else 9), 'L isubiu VI04, VI04, 1']
    return code


