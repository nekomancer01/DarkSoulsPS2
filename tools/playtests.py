#!/usr/bin/env python3
"""Writes the play tests: ISO test scripts that play as a person with a pad (src/testscript.c "option play").

  tools/playtests.py            -> ps2/proto/tests/iso_play_route.txt, iso_play_death.txt, iso_play_soak.txt

One spawn at boot (the Firelink bonfire's respawn point), then only pad input: `go` walks with the left stick relative
to the camera and turns the camera with the right stick, `pad cross` is the action button (bonfire, fog gate). No
teleports, no camera set from the script. A walker that makes no 0.3 m of progress for 5 s fails the run ("TEST error
stuck"), so a ladder, a missing object floor (TECH_DEBT collision-1) or a wall where the old route warped shows up as a
failure at that spot instead of being stepped over. "option god" keeps the walker alive (it cannot fight; Ame
2026-11-07: god mode is fine); deaths in the death run are scripted kills and falls.

Waypoints: the Firelink -> Burg start stretch of world_route.txt and the Burg -> Taurus fog stretch of
iso_burg_taurus.txt (tools/navroute.py over the game's navmesh). Each `spawn` those scripts used to step over a
ladder or a drop is a `go` to the same point here, with a comment.

Run (ISO from ./build-iso.sh, the ELF next to it for symbols):
  tools/q -m 2 PY tools/test-run.py build/proto.sym.elf ps2/proto/tests/iso_play_route.txt <out> --iso build/proto.iso \\
      --timeout 3600 --popin-max 10
  ... iso_play_death.txt <out> --iso build/proto.iso --timeout 3600
  ... iso_play_soak.txt <out> --iso build/proto.iso --timeout 7200 --hitch --soak
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TESTS = os.path.join(ROOT, "ps2", "proto", "tests")

BOOT = (-47.6, -59.9, 53.9, 1.6)          # Firelink, beside the bonfire (world_route.txt start)
RESPAWN = (-47.4, -59.8, 53.3)            # the bonfire's spawn point 復活ポイント00 (entity 1022960)
RESPAWN_ID = 1022960
CLIFF = (-40.1, 50.0)                     # 8 m from the respawn point at yaw 2.0: off the east cliff (lethal fall)
FOG = (52.6, -118.5)                      # Taurus Demon fog line on the tower top (ev_boss_taurus.txt)
SHOTS = {(-26.8, 26.7): "stairs", (-48.9, -11.0): "aqueduct_out", (-48.5, -35.5): "burg_start",
         (-7.2, -69.6): "bonfire_o0002", (24.4, -22.4): "bonfire_o0001", (6.2, -55.3): "street_1",
         (-4.3, -60.8): "street_2", (-0.5, -95.1): "street_end", (21.3, -105.9): "tower_base",
         (53.9, -114.5): "tower_1", (64.5, -116.8): "tower_2"}


def waypoints(path, start, stop):
    """(x, z, note) for each approach / spawn line from the line matching start up to the one matching stop"""
    out, on = [], False
    for ln in open(os.path.join(TESTS, path)):
        ln = ln.strip()
        on = on or bool(re.match(start, ln))
        if not on:
            continue
        if stop and re.match(stop, ln):
            break
        m = re.match(r"approach (-?[\d.]+),(-?[\d.]+)", ln)
        if m:
            out.append((float(m[1]), float(m[2]), ""))
            continue
        m = re.match(r"spawn (-?[\d.]+) (-?[\d.]+) (-?[\d.]+)", ln)
        if m:
            out.append((float(m[1]), float(m[3]), f"the old route warped here (y {m[2]}): ladder, drop or object floor"))
    return out


FIRELINK = waypoints("world_route.txt", r"approach -43\.1,52\.2", r"# step 2\.3 m")
# Measured 2026-11-07 (iso_play_route on main 1e5fab9): the walker cannot climb from Firelink to the aqueduct, a 6.7 m
# rise at (-22.9, 21.0) the old route warped over; so the death run stays on the Firelink side of it and the soak on
# the Burg side (aqueduct -> Burg start), until that rise and the Burg ladders can be walked (playable plan step 3).
CLIMB = next(i for i, p in enumerate(FIRELINK) if p[2])
FIRELINK_LOW, AQUEDUCT = FIRELINK[:CLIMB], FIRELINK[CLIMB + 1:]
RISE_TOP = (-22.9, -41.8, 21.0, 4.0)      # the top of that rise, on the way to the aqueduct (world_route.txt)
BURG = waypoints("iso_burg_taurus.txt", r"# step 2\.3 m", r"approach 52\.6,-118\.5 0\.4 1")


def header(title, lines, enemies=True, boot=BOOT):
    out = [f"# {l}" for l in [title] + lines]
    out += ["# Generated by tools/playtests.py: edit that, not this file.", "option hud", "option god", "option play"]
    if not enemies:
        out.append("option noenemies")
    out += ["wait 3", "shot boot", f"spawn {boot[0]} {boot[1]} {boot[2]} {boot[3]}", "wait 3", "stats"]
    return out


def walk(pts, shots=True, check_end=True):
    out = []
    for x, z, note in pts:
        if note:
            out.append(f"# {note}")
        out.append(f"go {x},{z}")
        name = SHOTS.get((x, z))
        if name and shots:
            out += ["wait 0.5", f"shot {name}", "stats"]
    if check_end and pts:
        x, z, _ = pts[-1]
        out.append(f"log reached {x},{z}")
    return out


def rest():
    """walk to the Firelink bonfire, rest (Cross), stand up (Circle)"""
    return ["go bonfire", "pad cross", "wait 3", f"ev expect respawn {RESPAWN_ID}",
            "pad circle", "wait 3"]


def route():
    fwd = FIRELINK + BURG
    back = [(x, z, n) for x, z, n in reversed(fwd[:-1])] + [(BOOT[0], BOOT[2], "")]
    out = header("Play route on the real disc: Firelink bonfire -> Undead Burg -> Taurus Demon fog and back, as a "
                 "person with a pad (enemies on).", [
                     "Fails on: a walker stuck 5 s (ladders and object floors are not in yet: the first one stops the run",
                     "there), any error line (OUT OF RAM, alloc FAILED, TLB miss, ...), more than 16 cells missing in a",
                     "frame, more than --popin-max near-level swaps on screen, an ev expect FAIL.",
                     "Boss fight itself: ev_boss_taurus.txt (once in, the fog keeps the player in)."])
    out += rest()
    out += walk(fwd)
    out += [f"go {FOG[0]},{FOG[1]} 0.4", "wait 1", "shot taurus_fog_near", "stats",
            f"check near {FOG[0]} 16.9 {FOG[1]} 1.0", "ev expect bossbar 0 -1", "log at the Taurus fog, walking back"]
    out += walk(back, shots=False)
    out += ["wait 1", "shot firelink_back", "stats", f"check near {BOOT[0]} {BOOT[1]} {BOOT[2]} 2.0", "ev summary", "end"]
    return out


def death():
    out = header("Play death run on the real disc: 20 deaths around Firelink, enemies on. Block seams (the aqueduct)",
                 ["are out of reach for now: a walker respawned at Firelink cannot climb the 6.7 m rise to the aqueduct",
                  "(see CLIMB in tools/playtests.py). Each death: back at the Firelink bonfire's spawn point",
                  "(respawn 1022960) within 12 s (TEST respawn ... settle; slower = TEST error), souls 0 and a 1000-soul",
                  "bloodstain, walk back to it as a player (go stain), souls back, RAM free back within 384 KB of the",
                  "baseline taken after the first rest. 5 deaths are falls off the east cliff, 15 kills along the route",
                  "(EMEVD's kill of the player). Every walk is pad input: a stuck walker fails as in the route."])
    out += rest()
    out += ["souls 1000", "wait 2", "ram mark"]
    reach = FIRELINK_LOW  # up to the foot of the rise to the aqueduct
    # 15 kills spread over the reachable stretch (each spot used once or twice)
    idx = [i % len(reach) for i in range(1, 16)]
    plan, k = [], 0
    for i in idx:
        plan.append(("kill", i))
        if len(plan) % 3 == 0 and k < 5:
            plan.append(("fall", None))
            k += 1
    while k < 5:
        plan.append(("fall", None))
        k += 1
    n = 0
    for kind, i in plan:
        n += 1
        out.append(f"# death {n}: " + ("fall off the east cliff" if kind == "fall" else f"kill at waypoint {i} "
                                       f"({reach[i][0]}, {reach[i][1]})"))
        path = [] if kind == "fall" else reach[:i + 1]
        out += walk(path, shots=False, check_end=False)
        if kind == "fall":
            out += [f"go {RESPAWN[0]},{RESPAWN[2]} 0.6", f"go {CLIFF[0]},{CLIFF[1]} 0.3"]
        else:
            out += ["wait 0.5", "kill"]
        out += ["wait 14", f"check deaths {n}", f"ev expect respawn {RESPAWN_ID}",
                f"check near {RESPAWN[0]} {RESPAWN[1]} {RESPAWN[2]} 1.5", "ev expect souls 0", "ev expect stain 1000",
                "ram check 384"]
        out += walk(path[:-1], shots=False, check_end=False)  # the stain lies at the last point: walk onto it
        out += ["go stain 0.4", "wait 1", "ev expect souls 1000", "ev expect stain -1"]
        if kind != "fall":
            out += walk(list(reversed(path[:-1])), shots=False, check_end=False)
            out.append(f"go {RESPAWN[0]},{RESPAWN[2]} 0.8")
    out += ["wait 2", "ram check 384", "shot death_end", "ev summary", "end"]
    return out


def soak(laps=30):
    out = header("Play soak on the real disc, 60 min and more of game time, enemies on: laps from the top of the rise",
                 ["above Firelink through the aqueduct (the Firelink / Burg west block seam) to the Burg start and",
                  "back, camera spins and idles at both ends. No deaths or rests: a respawn at Firelink cannot climb",
                  "back (see CLIMB in tools/playtests.py). Gate (test-run.py --hitch --soak): the last 10 min may",
                  "not be more than 20 % worse than the first in worst frame, frames over 50 ms, re-reads per",
                  "minute, LOD flips, pop-ins seen, or the largest free arena run / heap block."], boot=RISE_TOP)
    there = AQUEDUCT  # the top of the rise -> aqueduct -> Burg start
    back = [(x, z, n) for x, z, n in reversed(there[:-1])]
    for lap in range(laps):
        out += [f"log soak lap {lap} start"]
        out += walk(there, shots=False, check_end=False)
        out += [f"log soak lap {lap} far end", "rstick 1 0", "wait 4", "rstick -1 0", "wait 4", "rstick 0 0",
                "wait 20"]
        out += walk(back, shots=False, check_end=False)
        out += ["rstick 1 0", "wait 3", "rstick 0 0", "wait 15"]
    out += ["shot soak_end", "stats", "end"]
    return out


def main():
    for name, lines in (("iso_play_route", route()), ("iso_play_death", death()), ("iso_play_soak", soak())):
        path = os.path.join(TESTS, name + ".txt")
        open(path, "w").write("\n".join(lines) + "\n")
        print(f"{path}: {len(lines)} lines")


if __name__ == "__main__":
    main()
