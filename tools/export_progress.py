"""Export the new-game progression state (ps2/proto/src/progress.c) into a generated C header progress_data.h.
Source: CharaInitParam row of the starting class (default 3000 = Warrior): souls, soul level, the eight stats, humanity,
equipment ids (EquipParamWeapon / Protector / Accessory, -1 = empty) and the start items (EquipParamGoods) with counts.
Usage: export_progress.py <game dir> <out.h> [class row]"""
import os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import params

# Progress.equip[] slot order (progress.h EQ_*) -> CharaInitParam field
EQUIP = ["equip_Wep_Left", "equip_Wep_Right", "equip_Subwep_Left", "equip_Subwep_Right", "equip_Arrow", "equip_Bolt",
         "equip_SubArrow", "equip_SubBolt", "equip_Helm", "equip_Armer", "equip_Gaunt", "equip_Leg",
         "equip_Accessory01", "equip_Accessory02"]
# Status screen order VIT ATT END STR DEX RES INT FAI (CharaInitParam: Wil = attunement, Luc = resistance, Mag = int)
STATS = ["baseVit", "baseWil", "baseEnd", "baseStr", "baseDex", "baseLuc", "baseMag", "baseFai"]


def main():
    game, out = sys.argv[1], sys.argv[2]
    row = int(sys.argv[3]) if len(sys.argv) > 3 else 3000
    r = params.params("CharaInitParam", game)[row]
    items = [(r[f"item_{i:02d}"], r[f"itemNum_{i:02d}"]) for i in range(1, 11) if r[f"item_{i:02d}"] >= 0]
    L = ["/* Generated by tools/export_progress.py from the installed DSR files. Do not edit. */",
         "#ifndef PROGRESS_DATA_H", "#define PROGRESS_DATA_H", "",
         f"#define START_CLASS {row}  /* CharaInitParam {row} {r.name} */",
         f"#define START_SOULS {r['soul']}", f"#define START_LEVEL {r['soulLv']}",
         f"#define START_HUMANITY {r['baseHeroPoint']}",
         f"static const unsigned char start_stats[8] = {{{', '.join(str(r[s]) for s in STATS)}}};  /* VIT ATT END STR DEX RES INT FAI */",
         f"static const int start_equip[{len(EQUIP)}] = {{{', '.join(str(r[f]) for f in EQUIP)}}};",
         f"#define START_ITEMS {len(items)}",
         f"static const int start_items[{max(1, len(items))}][2] = {{{', '.join(f'{{{i}, {n}}}' for i, n in items) or '{0, 0}'}}};  /* EquipParamGoods id, count */",
         "", "#endif", ""]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, "w").write("\n".join(L))


if __name__ == "__main__":
    main()
