MAP_PLANES = MAP_OUT1 + MAP_OUT_QW  # 5 clip planes, written by vu1_begin
CLIP_TRIS = 32                      # clip batches (EE splits): scratch lives in the rest of the batch's own buffer
POLYA, POLYB, PV = 7 + 9 * CLIP_TRIS + 1, 7 + 9 * CLIP_TRIS + 1 + 27, 7 + 9 * CLIP_TRIS + 1 + 54

CLIP_DOC = """; VU1 microprogram (generated by tools/vu1/gen.py clip, do not edit): map batches that cross the near plane or the
; guard band (F4; replaces the EE clip pass map.c draw_clipped). Same input as vu1map.vsm (R3: header 0 {tris, cull,
; st scale K, edge fog slope a2 (ignored: clip batches are near the camera, never in map.c's edge band)}, 1 {origin xyz, step}, 2 A+D tag (EOP set), 3-5 TEX0 / TEX1 / TEST, 6 PRIM tag with NLOOP 3 + EOP,
; vertices at 7: s16 pos / u16 st / u8 colour, 3 qw each); batches of <= %(CT)d triangles (vu1_add_ex splits).
; Per triangle: view-space vertices (P, st K, colour as floats) into polygon buffer A at TOPS+%(PA)d; CLIP of (x F/G,
; y F/G, z - 2 near) against z (constants 6 / 7 as for vu1map.vsm); all three outside one plane: dropped; none
; flagged: drawn as is; otherwise Sutherland-Hodgman against the 5 planes at %(PL)d (near: z >= near; guard band:
; |x| <= z G / F, |y| <= z G / Fy), A <-> B at TOPS+%(PB)d; the polygon (<= 8 vertices) is projected into TOPS+%(PV)d
; (STQ, RGBAQ, XYZF2, screen float) and drawn as a fan; back faces (cull mask on the screen cross product) are not
; emitted at all. Every emitted triangle is one GIF packet kicked from output slot VI08 (%(O0)d / %(O1)d, shared with
; the map program: a slot is rewritten only after the other one's kick, which waits for this one).
; Hand written, unpipelined (only near / guard-band batches run it); MAC flags are read 4 cycles after their op.
""" % dict(CT=CLIP_TRIS, PA=POLYA, PB=POLYB, PV=PV, PL=MAP_PLANES, O0=MAP_OUT0, O1=MAP_OUT1)


def gen_clip1():
    """One-pass, unpipelined clip program (the structure before PR 2, with its clip core) for A/B:
    python3 gen.py clip1 > ab/vu1clip1.vsm"""
    out = [CLIP_DOC, '\t\t.vu', '\t\t.align 4', '\t\t.global VU1Clip_CodeStart', '\t\t.global VU1Clip_CodeEnd',
           'VU1Clip_CodeStart:']
    P = lambda u, l='NOP': out.append('\t%-31s\t%s' % (u.replace(', ', ','), l.replace(', ', ',')))
    L = lambda n: out.append('%s:' % n)
    N = lambda k=1: [P('NOP') for _ in range(k)]

    def dot(d, p):  # d.x = p . plane(VF30); MAC flags of d.x valid for fmand 4 cycles later
        P('mul VF19, %s, VF30' % p)
        P('adday.x ACC, VF19, VF19y')
        P('maddaz.x ACC, VF29, VF19z')
        P('maddw.x %s, VF29, VF19w' % d)
        N(3)

    for k in range(8):
        P('NOP', 'lq VF%02d, %d(VI00)' % (k + 1, k))
    P('NOP', 'xtop VI02')
    P('NOP', 'iaddiu VI01, VI00, %d' % MAP_OUT1)
    P('NOP', 'ilw.x VI04, 0(VI02)')
    P('NOP', 'ilw.y VI05, 0(VI02)')
    P('NOP', 'lq VF09, 0(VI02)')
    P('NOP', 'lq VF19, 1(VI02)')
    P('NOP', 'lq VF28, 6(VI02)')
    P('NOP', 'iaddiu VI10, VI02, 2')
    P('mulax ACC, VF01, VF19x', 'xgkick VI10')          # A+D header from the input buffer
    P('madday ACC, VF02, VF19y', 'iaddiu VI03, VI02, 7')
    P('maddaz ACC, VF03, VF19z', 'iaddiu VI09, VI00, 0x80')  # MAC sign x
    P('maddw VF04, VF04, VF00w')
    P('mulw VF01, VF01, VF19w')
    P('mulw VF02, VF02, VF19w')
    P('mulw VF03, VF03, VF19w')
    P('addw VF29, VF00, VF00w', 'ibeq VI08, VI01, clipTri')  # slot: keep slot 1, anything else -> slot 0
    P('NOP')
    P('NOP', 'iaddiu VI08, VI00, %d' % MAP_OUT0)
    L('clipTri')
    for v in range(3):
        o = 3 * v
        P('NOP', 'lq VF10, %d(VI03)' % o)
        P('NOP', 'lq VF11, %d(VI03)' % (o + 1))
        P('itof0.xyz VF10, VF10', 'lq VF12, %d(VI03)' % (o + 2))
        P('itof0.xy VF11, VF11')
        P('mulax ACC, VF01, VF10x')
        P('madday ACC, VF02, VF10y')
        P('maddaz ACC, VF03, VF10z')
        P('maddw VF13, VF04, VF00w')
        P('itof0 VF12, VF12')
        P('addz.z VF11, VF00, VF09z')
        P('max.w VF13, VF00, VF00')                     # P.w = 1
        P('mul.xyz VF16, VF13, VF07')
        P('mulz.w VF17, VF00, VF13z')
        P('add.xyz VF16, VF16, VF08', 'sq VF11, %d(VI02)' % (POLYA + o + 1))
        P('clipw.xyz VF16xyz, VF17w', 'sq VF12, %d(VI02)' % (POLYA + o + 2))
        P('NOP', 'sq VF13, %d(VI02)' % (POLYA + o))
    N(2)
    clip_core(out, 'clip', POLYA, POLYB, PV, 9, MAP_OUT0 + MAP_OUT1, PV + 32,
              ('mul.xyz VF16, VF10, VF07', 'add.xyz VF16, VF16, VF08'))
    out += ['\t\t.align 4', 'VU1Clip_CodeEnd:', '']
    return '\n'.join(out)


# CLIP flag bit of each clip plane at MAP_PLANES (near, guard band x+ x- y+ y-): near = -z (z - 2 near < -z), the
# guard-band planes +x, -x, +y, -y (x F/G > z ...)
PLANE_BIT = (5, 0, 1, 2, 3)


def clip_core(out, pfx, polya, polyb, pv, stride, slot_sum, need, reclip, tail=None):
    """Shared tail of the clip programs: after the three vertices of a triangle are in polygon buffer polya (TOPS
    relative; P, st K, colour floats) and their CLIPs issued: trivial reject, Sutherland-Hodgman against the planes
    some vertex is outside of (need: 5 TOPS-relative scratch words, one per plane; the others are skipped: a polygon
    clipped only by planes all three corners are inside of stays inside them), projection, fan, per-triangle kicks;
    then the next triangle: tail (the lines at <pfx>Skip; default VI03 += stride, VI04 -= 1, branch to <pfx>Tri) and
    the end. reclip: the two upper ops that make the CLIP input VF16.xyz from a polygon corner VF10 (w = z in VF17).
    """
    P = lambda u, l='NOP': out.append('\t%-31s\t%s' % (u.replace(', ', ','), l.replace(', ', ',')))
    L = lambda n: out.append('%s:' % n)
    N = lambda k=1: [P('NOP') for _ in range(k)]

    def dot(d, p):  # d.x = p . plane(VF30); MAC flags of d.x valid for fmand 4 cycles later
        P('mul VF19, %s, VF30' % p)
        P('adday.x ACC, VF19, VF19y')
        P('maddaz.x ACC, VF29, VF19z')
        P('maddw.x %s, VF29, VF19w' % d)
        N(3)

    k0 = len(out)
    P('NOP', 'fcand VI01, 262143')
    P('NOP', 'iadd VI10, VI01, VI00')
    for b in (0, 1, 2, 3, 5):  # trivial reject: all three vertices outside plane b
        imm = 0xFFFFFF & ~((1 << b) | (1 << (b + 6)) | (1 << (b + 12)))
        P('NOP', 'fcor VI01, %d' % imm)
        P('NOP')
        P('NOP', 'ibne VI01, VI00, clipSkip')
        P('NOP')
    P('NOP', 'iaddiu VI11, VI00, 3')
    P('NOP', 'iaddiu VI12, VI02, %d' % polya)
    P('NOP', 'ibeq VI10, VI00, clipProj')
    P('NOP', 'iaddiu VI13, VI02, %d' % polyb)
    P('NOP', 'iaddiu VI15, VI00, %d' % MAP_PLANES)
    # need[k] = some corner is outside plane k. CLIP compares with |z|, so a corner behind the eye (near flag) says
    # nothing about the guard band: such triangles test every plane
    for k, b in enumerate(PLANE_BIT):
        m = sum(1 << (c + 6 * v) for v in range(3) for c in {b, 5})
        P('NOP', 'fcand VI01, %d' % m)
        P('NOP', 'isw.x VI01, %d(VI02)' % (need + k))
    L('clipPlane')
    P('NOP', 'iadd VI01, VI15, VI02')
    P('NOP', 'ilw.x VI01, %d(VI01)' % (need - MAP_PLANES))
    N(3)
    P('NOP', 'ibeq VI01, VI00, clipNext')
    P('NOP')
    P('NOP', 'lq VF30, 0(VI15)')
    P('NOP', 'iadd VI01, VI11, VI11')
    P('NOP', 'iadd VI01, VI01, VI11')
    P('NOP', 'iadd VI01, VI01, VI12')
    P('NOP', 'iadd VI06, VI12, VI00')
    P('NOP', 'lq VF10, -3(VI01)')
    P('NOP', 'lq VF11, -2(VI01)')
    P('NOP', 'lq VF12, -1(VI01)')
    dot('VF13', 'VF10')
    P('NOP', 'fmand VI14, VI09')                         # prev outside
    P('NOP', 'iadd VI07, VI13, VI00')
    P('NOP', 'iaddiu VI10, VI00, 0')
    L('clipEdge')
    P('NOP', 'lq VF14, 0(VI06)')
    P('NOP', 'lq VF15, 1(VI06)')
    P('NOP', 'lq VF16, 2(VI06)')
    dot('VF17', 'VF14')
    P('NOP', 'fmand VI01, VI09')                         # cur outside
    P('NOP')
    P('sub.x VF18, VF13, VF17', 'ibeq VI01, VI14, clipNoCross')
    P('NOP')
    # the new corner is interpolated from the edge's inside end, whichever way the polygon walks the edge: the
    # neighbouring triangle (which walks it the other way) then gets the very same point (no cracks along the cut)
    P('sub.x VF19, VF17, VF13', 'ibne VI14, VI00, clipFromCur')
    P('NOP')
    N(2)

    def interp(a, b, da, dd):  # a + (b - a) da / dd, a = inside corner (P, st, colour), b = outside
        P('NOP', 'div Q, %sx, %sx' % (da, dd))
        P('sub VF19, %s, %s' % (b[0], a[0]), 'waitq')
        P('mulaw ACC, %s, VF00w' % a[0])
        P('maddq VF20, VF19, Q')
        P('sub VF19, %s, %s' % (b[1], a[1]))
        P('mulaw ACC, %s, VF00w' % a[1])
        P('maddq VF21, VF19, Q', 'sq VF20, 0(VI07)')
        P('sub VF19, %s, %s' % (b[2], a[2]))
        P('mulaw ACC, %s, VF00w' % a[2])
        P('maddq VF22, VF19, Q', 'sq VF21, 1(VI07)')
    interp(('VF10', 'VF11', 'VF12'), ('VF14', 'VF15', 'VF16'), 'VF13', 'VF18')
    P('NOP', 'b clipStored')
    P('NOP')
    L('clipFromCur')
    P('NOP')
    interp(('VF14', 'VF15', 'VF16'), ('VF10', 'VF11', 'VF12'), 'VF17', 'VF19')
    L('clipStored')
    N(3)
    P('NOP', 'sq VF22, 2(VI07)')
    P('NOP', 'iaddiu VI07, VI07, 3')
    P('NOP', 'iaddiu VI10, VI10, 1')
    L('clipNoCross')
    P('NOP', 'ibne VI01, VI00, clipCurOut')
    P('NOP')
    P('NOP', 'sq VF14, 0(VI07)')
    P('NOP', 'sq VF15, 1(VI07)')
    P('NOP', 'sq VF16, 2(VI07)')
    P('NOP', 'iaddiu VI07, VI07, 3')
    P('NOP', 'iaddiu VI10, VI10, 1')
    L('clipCurOut')
    P('NOP', 'move VF10, VF14')
    P('NOP', 'move VF11, VF15')
    P('NOP', 'move VF12, VF16')
    P('NOP', 'move VF13, VF17')
    P('NOP', 'iadd VI14, VI01, VI00')
    P('NOP', 'iaddiu VI06, VI06, 3')
    P('NOP', 'isubiu VI11, VI11, 1')
    P('NOP')
    P('NOP', 'ibne VI11, VI00, clipEdge')
    P('NOP')
    P('NOP', 'iadd VI11, VI10, VI00')                     # n = m, swap A / B
    P('NOP', 'iadd VI01, VI12, VI00')
    P('NOP', 'iadd VI12, VI13, VI00')
    P('NOP', 'iadd VI13, VI01, VI00')
    P('NOP', 'isubiu VI01, VI11, 3')
    P('NOP')
    P('NOP', 'ibltz VI01, clipSkip')
    P('NOP')
    L('clipNext')
    P('NOP', 'iaddiu VI15, VI15, 1')
    P('NOP', 'iaddiu VI01, VI00, %d' % (MAP_PLANES + 1))
    P('NOP')
    P('NOP', 'ibne VI15, VI01, clipNext2')
    P('NOP', 'ilw.x VI01, %d(VI02)' % need)
    N(3)
    P('NOP', 'ibeq VI01, VI00, clipNext2')
    P('NOP', 'iadd VI06, VI12, VI00')
    # after the near plane every corner has z >= near: CLIP the (<= 4) corners again and recompute need[1..4] exactly
    # (a 3-corner polygon leaves one stale result in the flags: at worst a plane is tested for nothing)
    P('NOP', 'iadd VI10, VI11, VI00')
    L('clipRe')
    P('NOP', 'lq VF10, 0(VI06)')
    N(3)
    P(reclip[0])
    P('mulz.w VF17, VF00, VF10z')
    N(2)
    P(reclip[1])
    N(3)
    P('clipw.xyz VF16xyz, VF17w', 'isubiu VI10, VI10, 1')
    P('NOP', 'iaddiu VI06, VI06, 3')
    P('NOP')
    P('NOP', 'ibne VI10, VI00, clipRe')
    P('NOP')
    N(2)
    for k, b in enumerate(PLANE_BIT[1:], 1):
        P('NOP', 'fcand VI01, %d' % sum(1 << (b + 6 * v) for v in range(4)))
        P('NOP', 'isw.x VI01, %d(VI02)' % (need + k))
    L('clipNext2')
    P('NOP', 'iaddiu VI01, VI00, %d' % (MAP_PLANES + 5))
    P('NOP')
    P('NOP', 'ibne VI15, VI01, clipPlane')
    P('NOP')
    L('clipProj')                                         # project the n vertices at VI12 into PV
    P('NOP', 'iadd VI06, VI12, VI00')
    P('NOP', 'iaddiu VI07, VI02, %d' % pv)
    P('NOP', 'iadd VI10, VI11, VI00')
    L('clipProjV')
    P('NOP', 'lq VF10, 0(VI06)')
    P('NOP', 'lq VF11, 1(VI06)')
    P('NOP', 'lq VF12, 2(VI06)')
    N(3)
    P('mulz.w VF20, VF05, VF10z', 'div Q, VF00w, VF10z')
    P('ftoi0 VF12, VF12')
    N(2)
    P('add.w VF20, VF20, VF06')
    N(3)
    P('max.w VF20, VF20, VF07', 'waitq')
    P('mulq.xy VF21, VF10, Q')
    P('addq.z VF21, VF00, Q')
    P('mulq.xyz VF11, VF11, Q')
    P('mini.w VF20, VF20, VF08')
    P('mul.xyz VF21, VF21, VF05')
    N(3)
    P('add.xyz VF20, VF21, VF06', 'sq VF11, 0(VI07)')
    N(3)
    P('ftoi4 VF22, VF20', 'sq VF12, 1(VI07)')
    N(3)
    P('NOP', 'sq VF22, 2(VI07)')
    P('NOP', 'sq VF20, 3(VI07)')
    P('NOP', 'iaddiu VI06, VI06, 3')
    P('NOP', 'iaddiu VI07, VI07, 4')
    P('NOP', 'isubiu VI10, VI10, 1')
    P('NOP')
    P('NOP', 'ibne VI10, VI00, clipProjV')
    P('NOP')
    P('NOP', 'iaddiu VI06, VI02, %d' % pv)                # fan (0, i, i + 1)
    P('NOP', 'iaddiu VI07, VI02, %d' % (pv + 4))
    P('NOP', 'isubiu VI10, VI11, 2')
    L('clipFan')
    P('NOP', 'lq VF20, 3(VI06)')
    P('NOP', 'lq VF21, 3(VI07)')
    P('NOP', 'lq VF22, 7(VI07)')
    N(3)
    P('sub.xyz VF14, VF21, VF20')
    P('sub.xyz VF15, VF22, VF20')
    N(3)
    P('opmula.xyz ACC, VF15, VF14')
    P('opmsub.xyz VF13, VF14, VF15')
    N(3)
    P('NOP', 'fmand VI01, VI05')
    P('NOP')
    P('NOP', 'ibne VI01, VI00, clipFanNext')
    P('NOP')
    P('NOP', 'sq VF28, 0(VI08)')
    for k, (base, off) in enumerate([('VI06', 0), ('VI07', 0), ('VI07', 4)]):
        for j in range(3):
            P('NOP', 'lq VF%02d, %d(%s)' % (20 + j, off + j, base))
        for j in range(3):
            P('NOP', 'sq VF%02d, %d(VI08)' % (20 + j, 1 + 3 * k + j))
    P('NOP')
    P('NOP', 'xgkick VI08')
    P('NOP', 'iaddiu VI01, VI00, %d' % slot_sum)  # the pass's two output slots: VI08 = sum - VI08
    P('NOP', 'isub VI08, VI01, VI08')
    L('clipFanNext')
    P('NOP', 'iaddiu VI07, VI07, 4')
    P('NOP', 'isubiu VI10, VI10, 1')
    P('NOP')
    P('NOP', 'ibne VI10, VI00, clipFan')
    P('NOP')
    L('clipSkip')
    for u, l in tail or [('NOP', 'iaddiu VI03, VI03, %d' % stride), ('NOP', 'isubiu VI04, VI04, 1'), ('NOP', 'NOP'),
                         ('NOP', 'ibne VI04, VI00, clipTri'), ('NOP', 'NOP'), ('NOP[E]', 'NOP'), ('NOP', 'NOP')]:
        P(u, l)
    for i in range(k0, len(out)):
        out[i] = re.sub(r'\bclip([A-Z]\w*)', pfx + r'\1', out[i])


# ------------------------------------------------------------------------------------------------ map clip, two pass
IDX_TRIS = 64         # vu1.c VU1_IDX_TRIS: triangles of an indexed batch (vu1clip's indexed entry lists all of them)
C2_SCR = 27 + 27 + 32 + 5 + 1 + IDX_TRIS + 1  # scratch at the end of the batch's own buffer
C2_POLYA = MAP_IN_QW - C2_SCR
C2_POLYB, C2_PV = C2_POLYA + 27, C2_POLYA + 54
NEED = C2_PV + 32     # clip_core: one word per clip plane
MODE = NEED + 5       # pass 2: 0 list batch, 1 indexed batch
LIST = MODE + 1       # pass 1: TOPS-relative address of each flagged triangle (indexed: its triangle stream qword), 0-ended
assert 7 + 9 * CLIP_TRIS <= C2_POLYA and LIST + IDX_TRIS + 1 <= MAP_IN_QW
CLIPI_MAX = C2_POLYA  # indexed batches through the indexed entry: header + vertices + triangle stream <= this

CLIP2_DOC = """; VU1 microprogram (generated by tools/vu1/gen.py clip, do not edit): map batches that cross the near plane or the
; guard band (VU1_CLIP). Same input and constants as vu1map2.vsm (list batches, <= %(CT)d triangles; vu1_add_ex
; splits) or, from the entry VU1Clip_Idx, as vu1mapi.vsm (indexed batches with header + vertices + triangle stream
; <= %(CM)d qwords; vu1_add_idx): the indexed pass 1 gathers each triangle's corners through its index qword.
; Pass 1: vu1map2's software-pipelined loop over every triangle: unflagged triangles are drawn there (one GIF packet
; each from output slot VI08 = %(O0)d / %(O1)d); a triangle with a flagged corner is kicked with ADC (not drawn) and
; its address (indexed: its index qword's) appended to a list at TOPS+%(LI)d (branch-free: the list pointer advances
; by the CLIP test's 0 / 1).
; Pass 2, per listed triangle: the three corners again (view space, st K, colour) into polygon buffer A at
; TOPS+%(PA)d, CLIPs, then the clip core: trivial reject, Sutherland-Hodgman against the planes at %(PL)d that some
; corner is outside of (after the near plane the corners are CLIPped again: CLIP compares with |z|), projection,
; fan, back faces dropped, one GIF packet per triangle (B at TOPS+%(PB)d, projected at TOPS+%(PV)d). A cut edge's
; new corner is interpolated from its inside end, so two triangles sharing the edge get the same point.
""" % dict(CT=CLIP_TRIS, CM=CLIPI_MAX, O0=MAP_OUT0, O1=MAP_OUT1, LI=LIST, PA=C2_POLYA, PB=C2_POLYB, PV=C2_PV,
           PL=MAP_PLANES)


def clip2_transform():
    """Pass 2: the listed triangle's corners at VI10 / VI11 / VI12 into polygon buffer A (P with .w 1, st with .z K,
    colour), CLIP of (x F/G, y F/G, z - 2 near) against z exactly as pass 1 (vu1map2) computes it"""
    code = []
    for v in range(3):
        o, a = 3 * v, 'VI1%d' % v
        code += ['L lq %%p%d, 0(%s)' % (v, a), 'L lq %%t%d, 1(%s)' % (v, a), 'L lq %%c%d, 2(%s)' % (v, a),
                 'U itof0.xyz %%p%d, %%p%d' % (v, v), 'U itof0.xy %%t%d, %%t%d' % (v, v), 'U itof0 %%c%d, %%c%d' % (v, v),
                 'U mulax ACC, VF01, %%p%d:x' % v, 'U madday ACC, VF02, %%p%d:y' % v, 'U maddaz ACC, VF03, %%p%d:z' % v,
                 'U maddw %%v%d, VF04, VF00w' % v,
                 'U mula.xyz ACC, %%v%d, VF07' % v, 'U maddw.xyz %%cl%d, VF08, VF00w' % v,
                 'U clipw.xyz %%cl%d:xyz, %%v%d:w' % (v, v),
                 'U addz.z %%t%d, VF00, VF09z' % v, 'U max.w %%v%d, VF00, VF00' % v,
                 'L sq %%t%d, %d(VI02)' % (v, C2_POLYA + o + 1), 'L sq %%c%d, %d(VI02)' % (v, C2_POLYA + o + 2),
                 'L sq %%v%d, %d(VI02)' % (v, C2_POLYA + o)]
    return code


def clip2_pass1(idx):
    body = map_body(idx=idx)  # + the list append, before the triangle pointer moves on
    k = body.index('L iaddiu VI03, VI03, %d' % (1 if idx else 9))
    body[k:k] = ['L isw.x VI03, 0(VI07)', 'L iadd VI07, VI07, VI01']
    label = 'c2Pass1I' if idx else 'c2Pass1'
    pairs, per, st, _ = schedule_body(body, ['VI10', 'VI11', 'VI12', 'VI13', 'VI14', 'VI15'], label,
                                      'ibne VI04, VI00, %s' % label, ['VF%02d' % i for i in range(11, 32)])
    return pairs, per


def gen_clip():
    pairs1, per1 = clip2_pass1(False)
    pairs1i, per1i = clip2_pass1(True)
    b = Block(clip2_transform(), ['VF%02d' % i for i in range(10, 28)], ['VI13'])
    b.schedule()
    b.allocate()
    pairs2 = b.pairs()
    print('clip pass 1: %d pairs, %.1f cycles / triangle (indexed %.1f); pass 2 transform %d pairs' %
          (len(pairs1), per1, per1i, len(pairs2)), file=sys.stderr)
    out = [CLIP2_DOC, '; pass 1 loop: %.0f cycles per triangle (indexed: %.0f) in the tools/vu1 timing model' %
           (per1, per1i), '', '\t\t.vu', '\t\t.align 4', '\t\t.global VU1Clip_CodeStart', '\t\t.global VU1Clip_Idx',
           '\t\t.global VU1Clip_CodeEnd', 'VU1Clip_CodeStart:']
    P = lambda u, l='NOP': out.append('\t%-31s\t%s' % (u.replace(', ', ','), l.replace(', ', ',')))

    def prologue(idx):
        for k in range(8):
            P('NOP', 'lq VF%02d, %d(VI00)' % (k + 1, k))
        P('NOP', 'xtop VI02')
        P('NOP', 'iaddiu VI01, VI00, %d' % MAP_OUT1)
